package com.zerostudio.idea.treesitter;

import com.zerostudio.idea.treesitter.annotations.GenerateNativeHeaders;
import dalvik.annotation.optimization.FastNative;

/**
 * @author Akash Yadav
 */
public class TreeSitter {

    private static int sLangVer = -1, sMinCompatLangVer = -1;
    private static String sEngineVersion = null; // 缓存版本字符串

    /**
     * Loads the <code>android-tree-sitter</code> native library using {@link
     * System#loadLibrary(String)}.
     */
    public static void loadLibrary() {
        System.loadLibrary("android-tree-sitter");
    }

    /** 获取手动维护的 Tree-sitter 引擎及 Git 哈希版本字符串。 格式规范：Vxx.xx-hasa 可直接为 Android TextView 等控件赋值。 */
    public static String getEngineVersion() {
        if (sEngineVersion == null) {
            sEngineVersion = Native.getEngineVersion();
        }
        return sEngineVersion;
    }

    /**
     * The latest ABI version that is supported by the current version of the library. When
     * Languages are generated by the Tree-sitter CLI, they are assigned an ABI version number that
     * corresponds to the current CLI version. The Tree-sitter library is generally
     * backwards-compatible with languages generated using older CLI versions, but is not
     * forwards-compatible.
     */
    public static int getLanguageVersion() {
        if (sLangVer == -1) {
            sLangVer = Native.getLanguageVersion();
        }

        return sLangVer;
    }

    /** The earliest ABI version that is supported by the current version of the library. */
    public static int getMinimumCompatibleLanguageVersion() {
        if (sMinCompatLangVer == -1) {
            sMinCompatLangVer = Native.getMinimumCompatibleLanguageVersion();
        }

        return sMinCompatLangVer;
    }

    @GenerateNativeHeaders(fileName = "meta")
    private static final class Native {

        @FastNative
        static native int getLanguageVersion();

        @FastNative
        static native String getEngineVersion();

        /** The earliest ABI version that is supported by the current version of the library. */
        @FastNative
        static native int getMinimumCompatibleLanguageVersion();
    }
}